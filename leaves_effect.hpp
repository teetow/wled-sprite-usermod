// Persistent autumn litter and occasional canopy shedding. The host owns the
// calendar, snow coverage and tree palette; this effect owns only motion/time.
// Two instances share this effect: a ground band and a narrow tree-foot strip.
#include "flow_field.hpp"
#include "leaf_exchange.hpp"

constexpr uint32_t LEAVES_MAGIC = 0x4c45414aUL;
constexpr unsigned LEAVES_CAPACITY = 32;
constexpr unsigned LEAVES_SHED_CAPACITY = 2;
constexpr uint32_t LEAF_SPAWN_MS = 10000;
constexpr uint32_t LEAF_FALL_MS = 2000;
constexpr uint32_t LEAF_DESPAWN_MS = 10000;
// Ground litter: opacity floor, and the ramp from it to full strength for
// leaves that settle in place.
constexpr float LEAF_MIN_OPACITY = 0.5f;
constexpr uint32_t LEAF_GROUND_FADE_MS = 2000;
// Gap before a different ground leaf replaces one blown off the panel.
constexpr uint32_t LEAF_RETURN_MIN_MS = 500;
constexpr uint32_t LEAF_RETURN_SPAN_MS = 3500;
// Per-leaf flutter: correlation time, strength along the panel as a fraction
// of local air speed, and across rows per unit of air speed.
constexpr float LEAF_FLUTTER_SECONDS = 0.6f;
constexpr float LEAF_FLUTTER_X = 0.35f;
constexpr float LEAF_FLUTTER_ROWS = 0.12f; // rows/s per unit of air speed
// Soft separation between moving leaves: reach in LEDs, and peak steering
// speed in LEDs per second.
constexpr float LEAF_AVOID_RADIUS = 3.5f;
constexpr float LEAF_AVOID_STRENGTH = 2.0f;
// A rising leaf this many rows clear of the horizon is handed to the airborne
// Wind layer, when that layer is running and has room.
constexpr float LEAF_LIFT_HANDOFF_ROWS = 2.0f;
// Sideways drift of an airborne leaf that has no free spot to land on.
constexpr float LEAF_DRIFT_LEDS_PER_SECOND = 2.0f;

struct LeafParticle {
  float x, y, sourceY;
  float worldX, depth, vx, vy, height, vz;
  float flutterX, flutterY;
  uint8_t seed;
  uint32_t age, wait;
  uint8_t color, stage;
  bool active, falling;
};

struct LeavesState {
  uint32_t magic, lastUpdate, random;
  uint16_t width, height, groundTop;
  bool shedding;
  uint8_t spawnerCount;
  LeafParticle particles[LEAVES_CAPACITY];
  FlowField flow;
};

uint32_t leafRandom(LeavesState &state, uint32_t limit) {
  state.random ^= state.random << 13;
  state.random ^= state.random >> 17;
  state.random ^= state.random << 5;
  return limit ? state.random % limit : 0;
}

// c2 is seasonal taper in shedding mode: 0 is peak, 255 stops new births.
// Stretch only the quiet interval; fade and gravity timings remain fixed.
uint32_t shedLeafWait(LeavesState &state, const Segment &seg) {
  const uint32_t activeMs = LEAF_SPAWN_MS + LEAF_FALL_MS + LEAF_DESPAWN_MS;
  const uint32_t peakCycleMs = activeMs + 12000 + leafRandom(state, 10001);
  return peakCycleMs * 255 / max<unsigned>(1, 255 - seg.custom2) - activeMs;
}

// Same coordinate ranks as Neoblaster's tree.ts: emit only from a leaf still
// present in the generated 6x7 canopy, and only once that leaf has turned.
float leafCellNoise(int x, int y, int salt) {
  uint32_t h = uint32_t(x + 1) * 0x27d4eb2dU ^ uint32_t(y + 1) * 0x165667b1U ^ uint32_t(salt + 1) * 0x9e3779b9U;
  h ^= h >> 15; h *= 0x85ebca6bU;
  h ^= h >> 13; h *= 0xc2b2ae35U;
  h ^= h >> 16;
  return double(h) / 4294967296.0;
}

bool spawnShedLeaf(LeavesState &state, const Segment &seg, LeafParticle &leaf) {
  static const char *canopy[] = {"..LL..", ".LLLL.", "LLLLLL", "LLLLLL", ".L.LL."};
  uint8_t candidates[30];
  unsigned count = 0;
  for (int y = 0; y < 5 && y < state.height - 1; y++) {
    for (int x = 0; x < 6 && x < state.width; x++) {
      const float turn = max(0.0f, min(0.9f, leafCellNoise(x, y, 2) * 0.75f - (1.0f - y / 7.0f) * 0.1f));
      if (canopy[y][x] == 'L' && leafCellNoise(x, y, 1) < seg.custom1 / 255.0f
          && seg.custom3 / 31.0f > turn + 0.125f) candidates[count++] = y * 6 + x;
    }
  }
  if (!count) return false;
  uint8_t spaced[30];
  unsigned spacedCount = 0;
  for (unsigned i = 0; i < count; i++) {
    const int column = candidates[i] % 6;
    bool separated = true;
    for (unsigned j = 0; j < state.spawnerCount; j++) {
      const LeafParticle &other = state.particles[j];
      if (&other != &leaf && other.active && abs(column - int(other.x)) < 2) {
        separated = false;
        break;
      }
    }
    if (separated) spaced[spacedCount++] = candidates[i];
  }
  const unsigned cell = spacedCount ? spaced[leafRandom(state, spacedCount)]
                                    : candidates[leafRandom(state, count)];
  leaf = {};
  leaf.x = cell % 6;
  leaf.y = cell / 6;
  leaf.sourceY = leaf.y;
  leaf.color = unsigned(leafCellNoise(cell % 6, cell / 6, 3) * 3) % 3;
  leaf.stage = 1;
  leaf.active = true;
  return true;
}

// AI: below section was generated by an AI
inline float leafPerspective(float depth) { return 1 / (3 - 2 * depth); }

void projectGroundLeaf(const LeavesState &state, LeafParticle &leaf) {
  const float scale = leafPerspective(leaf.depth);
  leaf.x = state.width * 0.5f + (leaf.worldX - state.width * 0.5f) * scale;
  const float span = float(state.height - state.groundTop - 1);
  leaf.y = state.groundTop + span * (scale - 1.0f / 3.0f) * 1.5f - leaf.height * scale;
}

// Inverse of projectGroundLeaf for a grounded leaf on the given screen row.
float groundDepthForRow(const LeavesState &state, float row) {
  const float span = max(1.0f, float(state.height - state.groundTop - 1));
  const float scale = 1.0f / 3.0f + 2.0f / 3.0f * (row - state.groundTop) / span;
  return flowClamp((3 - 1 / scale) * 0.5f, 0, 1);
}

// Depth-domain units (24 across the band) covered by one LED row at this
// depth: rows advance 3 * span * scale^2 per unit of normalized depth.
inline float groundDepthPerRow(const LeavesState &state, float depth) {
  const float scale = leafPerspective(depth);
  const float span = max(1.0f, float(state.height - state.groundTop - 1));
  return 24.0f / (3.0f * span * scale * scale);
}

// The LED a leaf lights, rounded exactly as drawLeaf rounds it.
inline bool leafPixel(const LeavesState &state, const LeafParticle &leaf, int &px, int &py) {
  px = int(floorf(leaf.x + 0.5f));
  py = int(floorf(leaf.y + 0.5f));
  return px >= 0 && py >= 0 && px < state.width && py < state.height;
}

// The spacing invariant: no two visible ground leaves share or touch an LED,
// diagonals included. Every placement and every move is checked against it,
// so a pile-up can never draw a solid streak.
bool leafPixelFree(const LeavesState &state, const LeafParticle &self, int px, int py) {
  for (const LeafParticle &other : state.particles) {
    if (!other.active || &other == &self) continue;
    int ox, oy;
    if (leafPixel(state, other, ox, oy) && abs(ox - px) < 2 && abs(oy - py) < 2) return false;
  }
  return true;
}

// Squared distance to the nearest visible leaf, or -1 when the LED would
// break the spacing invariant. With only a few leaves, different rows must
// not excuse matching columns.
float groundCandidateDistance(const LeavesState &state, const LeafParticle &leaf,
                              float target, int x, int y) {
  if (!leafPixelFree(state, leaf, x, y)) return -1.0f;
  float nearest = 1.0e9f;
  for (const LeafParticle &other : state.particles) {
    if (!other.active || &other == &leaf) continue;
    const float dx = x - other.x, dy = y - other.y;
    nearest = min(nearest, dx * dx + (target <= 8.0f ? 0.0f : dy * dy));
  }
  return nearest;
}

void placeGroundLeaf(LeavesState &state, LeafParticle &leaf, float x, uint16_t row) {
  leaf = {};
  leaf.x = x;
  leaf.y = row;
  leaf.color = leafRandom(state, 3);
  leaf.seed = leafRandom(state, 256);
  leaf.depth = groundDepthForRow(state, row);
  leaf.worldX = state.width * 0.5f + (leaf.x - state.width * 0.5f) / leafPerspective(leaf.depth);
  leaf.active = true;
}

bool spawnGroundLeaf(LeavesState &state, LeafParticle &leaf, float target) {
  // Best-candidate blue noise: place each new leaf as far as possible from
  // visible litter. A fixed set of random candidates keeps this cheap; when
  // none satisfies the spacing invariant the leaf waits and tries again.
  float bestDistance = -1.0f;
  uint16_t bestX = 0, bestY = 0;
  for (unsigned trial = 0; trial < 24; trial++) {
    const uint16_t x = leafRandom(state, state.width);
    const uint16_t y = state.groundTop + leafRandom(state, state.height - state.groundTop);
    const float nearest = groundCandidateDistance(state, leaf, target, x, y);
    if (nearest > bestDistance) {
      bestDistance = nearest;
      bestX = x;
      bestY = y;
    }
    if (nearest == 1.0e9f) break; // the first leaf remains uniformly random
  }
  if (bestDistance < 0) return false;
  placeGroundLeaf(state, leaf, bestX + leafRandom(state, 64) / 256.0f, bestY);
  return true;
}

// Carried in from upwind: the entry row is the free one farthest from the
// litter already near that edge, so arrivals do not queue up in one row.
bool enterGroundLeafFromEdge(LeavesState &state, LeafParticle &leaf, float target, bool blowLeft) {
  const unsigned rows = state.height - state.groundTop;
  const unsigned offset = leafRandom(state, rows); // random order breaks ties
  const int column = blowLeft ? state.width - 1 : 0;
  float bestDistance = -1.0f;
  uint16_t bestRow = 0;
  for (unsigned i = 0; i < rows; i++) {
    const uint16_t row = state.groundTop + (i + offset) % rows;
    const float nearest = groundCandidateDistance(state, leaf, target, column, row);
    if (nearest > bestDistance) {
      bestDistance = nearest;
      bestRow = row;
    }
  }
  if (bestDistance < 0) return false;
  placeGroundLeaf(state, leaf, blowLeft ? state.width - 0.51f : -0.49f, bestRow);
  leaf.age = LEAF_GROUND_FADE_MS; // already fully visible as it crosses the edge
  return true;
}

// A leaf blown off the panel is gone; nothing wraps. A different leaf arrives
// after an irregular gap, so departures and arrivals do not pair up.
void retireGroundLeaf(LeavesState &state, LeafParticle &leaf) {
  leaf.active = false;
  leaf.stage = 1; // returning: the next arrival may blow in from upwind
  leaf.wait = LEAF_RETURN_MIN_MS + leafRandom(state, LEAF_RETURN_SPAN_MS + 1);
}

bool arriveGroundLeaf(LeavesState &state, LeafParticle &leaf, const Segment &seg, float target) {
  // Initial litter and calm-weather arrivals settle in place. Once wind can
  // move litter, most arrivals are carried in from upwind at a fresh depth.
  const bool carried = leaf.stage == 1 && max(seg.speed, seg.custom2) >= 30
    && leafRandom(state, 100) < 65;
  if (carried && enterGroundLeafFromEdge(state, leaf, target, seg.check1)) return true;
  if (spawnGroundLeaf(state, leaf, target)) return true;
  leaf.wait = 250 + leafRandom(state, 501); // no free spot yet; retry shortly
  return false;
}

// Enforce the spacing invariant for one move. The mover yields: it glances
// off one row in depth, or else stays where it was and loses its speed. A
// neighbour never displaces a resting leaf. An airborne leaf may also slide
// one or two LEDs along the panel, so it can always come down beside a
// resting leaf. When every nearby landing spot is taken, it holds its
// height and drifts along the panel until a gap opens below it.
void keepGroundLeafSpacing(LeavesState &state, LeafParticle &leaf, const LeafParticle &before, float seconds) {
  int px, py;
  if (!leafPixel(state, leaf, px, py) || leafPixelFree(state, leaf, px, py)) return;
  int bx, by;
  // Should the invariant somehow be broken already, never freeze a leaf.
  if (leafPixel(state, before, bx, by) && !leafPixelFree(state, leaf, bx, by)) return;
  const int depthSide = leaf.vy > 0 ? 1 : leaf.vy < 0 ? -1 : (leaf.seed & 1 ? 1 : -1);
  const int along = leaf.vx < 0 ? -1 : 1;
  const int airborne = leaf.height > 0;
  const struct { int rows, columns; } moves[] = {
    {depthSide, 0}, {-depthSide, 0},
    {0, along * airborne}, {0, -along * airborne}, {0, 2 * along * airborne}, {0, -2 * along * airborne},
  };
  for (const auto &move : moves) {
    if (move.rows == 0 && move.columns == 0) continue;
    LeafParticle trial = leaf;
    if (move.rows && !airborne) {
      const int row = py + move.rows;
      if (row < state.groundTop || row >= state.height) continue;
      trial.depth = groundDepthForRow(state, row);
    } else if (move.rows) {
      trial.depth = flowClamp(trial.depth + move.rows * groundDepthPerRow(state, trial.depth) / 24.0f, 0, 1);
    }
    trial.worldX += move.columns / leafPerspective(trial.depth);
    projectGroundLeaf(state, trial);
    int tx, ty;
    if (trial.x < -0.5f || trial.x >= state.width - 0.5f) continue;
    if (!leafPixel(state, trial, tx, ty)) { if (airborne) { leaf = trial; return; } continue; }
    if ((tx != px || ty != py) && leafPixelFree(state, leaf, tx, ty)) {
      leaf.worldX = trial.worldX;
      leaf.depth = trial.depth;
      leaf.x = trial.x;
      leaf.y = trial.y;
      return;
    }
  }
  leaf.worldX = before.worldX;
  leaf.depth = before.depth;
  leaf.height = before.height;
  leaf.x = before.x;
  leaf.y = before.y;
  leaf.vx = leaf.vy = leaf.vz = 0;
  if (!airborne) return;
  const int drift = leaf.seed & 1 ? 1 : -1; // a fixed side per leaf, so it does not dither
  for (const int side : {drift, -drift}) {
    LeafParticle trial = leaf;
    trial.worldX += side * LEAF_DRIFT_LEDS_PER_SECOND * seconds / leafPerspective(trial.depth);
    projectGroundLeaf(state, trial);
    int tx, ty;
    if (trial.x < -0.5f || trial.x >= state.width - 0.5f) continue;
    if (leafPixel(state, trial, tx, ty) && !leafPixelFree(state, leaf, tx, ty)) continue;
    leaf.worldX = trial.worldX;
    leaf.x = trial.x;
    return;
  }
}

// Soft separation: a moving leaf steers around visible neighbours within a
// few LEDs, slowing as it closes in and turning through depth to pass. This
// keeps flowing litter spaced like Poisson-disc samples; the hard spacing
// rule above only catches what this misses. Returns world-X and depth
// velocities. Same-row neighbours are passed on a side chosen per leaf.
void groundLeafAvoidance(const LeavesState &state, const LeafParticle &leaf, float &awayX, float &awayDepth) {
  float screenX = 0, screenY = 0;
  for (const LeafParticle &other : state.particles) {
    if (!other.active || &other == &leaf) continue;
    const float dx = leaf.x - other.x, dy = leaf.y - other.y;
    const float distance = sqrtf(dx * dx + dy * dy);
    if (distance >= LEAF_AVOID_RADIUS) continue;
    const float push = (LEAF_AVOID_RADIUS - distance) / LEAF_AVOID_RADIUS;
    screenX += push * (distance > 0.01f ? dx / distance : 0.0f);
    const float side = fabsf(dy) > 0.3f ? dy / max(distance, 0.01f) : (leaf.seed & 1 ? 1.0f : -1.0f);
    screenY += push * side;
  }
  // The band's top and bottom edges push back like mirrored neighbours, at
  // half strength. Without them, a leaf by an edge is only pushed from
  // inside and the edge rows collect litter; at full strength the rows just
  // inside the edges do.
  const float edges[2] = {state.groundTop - 0.5f, state.height - 0.5f};
  for (const float edge : edges) {
    const float distance = 2 * fabsf(leaf.y - edge);
    if (distance >= LEAF_AVOID_RADIUS) continue;
    screenY += 0.5f * (LEAF_AVOID_RADIUS - distance) / LEAF_AVOID_RADIUS * (leaf.y > edge ? 1.0f : -1.0f);
  }
  awayX = LEAF_AVOID_STRENGTH * screenX / leafPerspective(leaf.depth);
  awayDepth = LEAF_AVOID_STRENGTH * screenY * groundDepthPerRow(state, leaf.depth);
}

void moveGroundLeaf(LeavesState &state, LeafParticle &leaf, const Segment &seg, float seconds, const GustTuning &tuning = DEFAULT_GUST_TUNING) {
  const LeafParticle before = leaf;
  const float fx = (leaf.worldX + state.width) / (state.width * 3.0f) * FLOW_WIDTH - 0.5f;
  const float fy = leaf.depth * FLOW_HEIGHT - 0.5f;
  const float pulse = gustFieldStrength(leaf.x + seg.start, strip.now, seg.check1, seg.custom1, tuning);
  const float meanMps = seg.speed / 10.0f, gustMps = max(seg.speed, seg.custom2) / 10.0f;
  const float kick = (groundFlowSpeed(gustMps) - groundFlowSpeed(meanMps)) * pulse;
  float airX = flowSample(state.flow.u, fx, fy) + (seg.check1 ? -kick : kick);
  float airY = flowSample(state.flow.v, fx, fy);
  const float updraft = airY; // lift reads the resolved flow, never the flutter
  // Each leaf's own flutter: small-scale turbulence the 16x8 grid cannot
  // resolve. Without it, neighbours in one grid cell travel in lockstep and
  // a convoy never breaks up. Unit-variance Ornstein-Uhlenbeck noise, scaled
  // by the local air speed, so still air adds nothing.
  const float airSpeed = sqrtf(airX * airX + airY * airY);
  const float decay = min(1.0f, seconds / LEAF_FLUTTER_SECONDS);
  const float noise = sqrtf(6.0f * decay); // uniform [-1, 1] has variance 1/3
  leaf.flutterX += -leaf.flutterX * decay + noise * (leafRandom(state, 2001) / 1000.0f - 1);
  leaf.flutterY += -leaf.flutterY * decay + noise * (leafRandom(state, 2001) / 1000.0f - 1);
  airX += leaf.flutterX * airSpeed * LEAF_FLUTTER_X;
  // Depth flutter is sized in screen rows, not depth. A random walk settles
  // evenly over whatever it steps in, and stepping evenly in depth would pile
  // litter onto the horizon rows, where perspective packs the most depth.
  airY += leaf.flutterY * airSpeed * LEAF_FLUTTER_ROWS * groundDepthPerRow(state, leaf.depth);
  const float weight = leaf.seed / 255.0f;
  const float grip = 0.025f + 3.8f * weight * weight;
  const float speed = sqrtf(airX * airX + airY * airY);
  const float responseMs = pulse > 0 ? tuning.responseMs : tuning.settleMs;
  const float coupling = 1000.0f / responseMs * (0.8f + 0.4f * (1 - weight));
  // Static friction holds sheltered leaves; moving ones coast and settle.
  const float mobility = leaf.height > 0 ? 1 : flowClamp((speed - grip) / max(0.05f, speed), 0, 1);
  float awayX = 0, awayDepth = 0;
  if (mobility > 0) groundLeafAvoidance(state, leaf, awayX, awayDepth);
  leaf.vx += ((airX + awayX) * mobility - leaf.vx) * min(1.0f, coupling * seconds);
  leaf.vy += ((airY + awayDepth) * mobility - leaf.vy) * min(1.0f, coupling * seconds);
  if (mobility == 0 && fabsf(leaf.vx) < 0.015f && fabsf(leaf.vy) < 0.015f) leaf.vx = leaf.vy = 0;
  const float localMps = meanMps + (gustMps - meanMps) * pulse;
  const float lift = flowClamp((localMps - (7.8f + 1.4f * weight)) / 1.2f, 0, 1);
  // A positive updraft proxy from a rotating patch can lift a leaf only when
  // local wind crosses 8–10 m/s. Gravity acts independently of ground depth.
  const float acceleration = lift * max(0.0f, updraft) * 6.0f * (1 + max(0.0f, localMps - 10) * 0.12f) - (1.6f + 0.8f * weight) - leaf.vz * 1.2f;
  leaf.vz += acceleration * seconds;
  leaf.height += leaf.vz * seconds;
  if (leaf.height <= 0) { leaf.height = 0; leaf.vz = max(0.0f, leaf.vz); }
  if (leaf.height > 12) { leaf.height = 12; leaf.vz = min(0.0f, leaf.vz); }
  leaf.worldX += leaf.vx * seconds;
  leaf.depth += leaf.vy * seconds / 24.0f;
  // Depth edges reflect. Clamping used to pin over half the litter to the
  // horizon and front rows; turning the leaf and its flutter back inward
  // lets it drift away from the edge instead.
  if (leaf.depth < 0) {
    leaf.depth = min(1.0f, -leaf.depth);
    leaf.vy = fabsf(leaf.vy);
    leaf.flutterY = fabsf(leaf.flutterY);
  } else if (leaf.depth > 1) {
    leaf.depth = max(0.0f, 2 - leaf.depth);
    leaf.vy = -fabsf(leaf.vy);
    leaf.flutterY = -fabsf(leaf.flutterY);
  }
  projectGroundLeaf(state, leaf);
  if (leaf.x < -0.5f || leaf.x >= state.width - 0.5f) { retireGroundLeaf(state, leaf); return; }
  // Clear of the horizon and still rising: the leaf carries on as an airborne
  // particle at the same LED, color and speed, instead of being capped here.
  if (leaf.vz > 0 && leaf.y < state.groundTop - LEAF_LIFT_HANDOFF_ROWS
      && leafExchangeAlive(leafExchange.airSeen, leafExchange.airSeenAt) && leafExchange.airRoom > 0) {
    const float scale = leafPerspective(leaf.depth);
    if (postLeafHandoff(leafExchange.toAir, seg.start + leaf.x, seg.startY + leaf.y,
                        leaf.vx * scale, -leaf.vz * scale, leaf.color)) {
      leafExchange.airRoom--;
      leafExchange.liftsOffered++;
      retireGroundLeaf(state, leaf);
      return;
    }
  }
  keepGroundLeafSpacing(state, leaf, before, seconds);
}

// Airborne leaves that came down over the ground band settle as litter, fully
// visible and keeping their color and horizontal momentum. A slot is free when
// it is within the seasonal density and holds no leaf; taking one that was
// waiting to refill also cancels that refill, so the density holds.
void settleAirborneLeaves(LeavesState &state, const Segment &seg, float target) {
  for (LeafHandoff &handoff : leafExchange.toGround) {
    const bool live = leafHandoffLive(handoff);
    handoff.pending = false;
    if (!live) continue;
    const float x = handoff.x - seg.start;
    const int row = int(floorf(handoff.y - seg.startY + 0.5f));
    if (row < state.groundTop || row >= state.height || x < -0.5f || x >= state.width - 0.5f) continue;
    for (unsigned i = 0; i < LEAVES_CAPACITY && target - i >= 1.0f; i++) {
      LeafParticle &slot = state.particles[i];
      if (slot.active) continue;
      if (!leafPixelFree(state, slot, int(floorf(x + 0.5f)), row)) break;
      placeGroundLeaf(state, slot, x, row);
      slot.color = handoff.color % 3;
      slot.age = LEAF_GROUND_FADE_MS;
      slot.vx = handoff.vx / leafPerspective(slot.depth);
      leafExchange.landingsTaken++;
      break;
    }
  }
}

// Tell the Wind layer where the ground is, which LEDs litter occupies and how
// many more leaves it can take, so it only lands leaves that will fit.
void publishGroundLitter(const LeavesState &state, const Segment &seg, float target) {
  LeafExchange &exchange = leafExchange;
  exchange.groundSeen = true;
  exchange.groundSeenAt = strip.now;
  exchange.groundTop = seg.startY + state.groundTop;
  exchange.groundBottom = seg.startY + state.height;
  exchange.groundLeft = seg.start;
  exchange.groundRight = seg.start + state.width;
  for (uint64_t &row : exchange.groundLit) row = 0;
  unsigned active = 0;
  for (const LeafParticle &leaf : state.particles) {
    if (!leaf.active) continue;
    active++;
    int px, py;
    if (!leafPixel(state, leaf, px, py)) continue;
    const int x = seg.start + px, y = seg.startY + py;
    if (x < int(LEAF_EXCHANGE_MAX_COLUMNS) && y < int(LEAF_EXCHANGE_MAX_ROWS)) exchange.groundLit[y] |= uint64_t(1) << x;
  }
  const int room = int(floorf(target)) - int(active);
  exchange.groundRoom = uint8_t(max(0, min(255, room)));
}
